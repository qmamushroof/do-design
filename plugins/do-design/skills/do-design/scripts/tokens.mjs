#!/usr/bin/env node
// tokens.json → tokens.css (+ --tailwind: tokens.tailwind.css, + --figma: tokens.figma.json)
// Usage: node tokens.mjs <tokens.json> <outDir> [--tailwind] [--figma]
import { writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { loadTokens, flatten, resolver } from './lib/tokens.mjs';
import { parseColor, toHex } from './lib/color.mjs';

const [src, outDir = '.', ...flags] = process.argv.slice(2);
if (!src) { console.error('Usage: node tokens.mjs <tokens.json> <outDir> [--tailwind] [--figma]'); process.exit(2); }

const tokens = loadTokens(src);
const entries = flatten(tokens);
const { asVar, literal } = resolver(entries);
mkdirSync(outDir, { recursive: true });

const decl = (list, theme) => list.map((e) => `  ${e.name}: ${asVar(e.value, theme)};`).join('\n');
const base = entries.filter((e) => !e.theme);
const light = entries.filter((e) => e.theme === 'light');
const dark = entries.filter((e) => e.theme === 'dark');

let css = `/* Generated by do-design from ${src.replace(/\\/g, '/')} — edit tokens.json, not this file. */\n`;
css += `:root {\n  color-scheme: light dark;\n${decl(base, null)}\n${decl(light, 'light')}\n}\n`;
if (dark.length) {
  css += `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${decl(dark, 'dark').replace(/^/gm, '  ')}\n  }\n}\n`;
  css += `:root[data-theme="dark"] {\n  color-scheme: dark;\n${decl(dark, 'dark')}\n}\n`;
  css += `:root[data-theme="light"] {\n  color-scheme: light;\n}\n`;
}
writeFileSync(join(outDir, 'tokens.css'), css);
const written = ['tokens.css'];

if (flags.includes('--tailwind')) {
  // Tailwind v4 namespaces. Themed values reference the runtime var; static ones are literal.
  const ns = { color: 'color', font: 'font', 'font-size': 'text', weight: 'font-weight', leading: 'leading', tracking: 'tracking',
    space: 'spacing', radius: 'radius', elevation: 'shadow', ease: 'ease', breakpoint: 'breakpoint' };
  const seen = new Set();
  const lines = [];
  for (const e of [...base, ...light]) {
    const group = e.path[0];
    if (!ns[group]) continue;
    const key = e.name.replace(/^--/, '').replace(group === 'color' ? /^/ : new RegExp(`^${group}-`), '');
    const twName = `--${ns[group]}-${key}`;
    if (seen.has(twName)) continue;
    seen.add(twName);
    const value = String(e.theme || group === 'color' ? `var(${e.name})` : literal(e.value, null));
    if (twName === e.name && value.startsWith('var(')) continue; // would self-reference
    lines.push(`  ${twName}: ${value};`);
  }
  writeFileSync(join(outDir, 'tokens.tailwind.css'),
    `/* Generated by do-design. Import after tailwindcss and tokens.css. */\n@custom-variant dark (&:where([data-theme=dark], [data-theme=dark] *));\n@theme inline {\n${lines.join('\n')}\n}\n`);
  written.push('tokens.tailwind.css');
}

if (flags.includes('--figma')) {
  // Figma variables-style export: collections with modes.
  const varOf = (e, theme) => {
    const v = literal(e.value, theme);
    const c = e.path[0] === 'color' ? parseColor(v) : null;
    return c ? toHex(c) : v;
  };
  const primitives = base.map((e) => ({ name: e.path.filter((p) => p !== 'primitive').join('/'), type: e.type ?? 'string', value: varOf(e, null) }));
  const semantic = light.map((e) => {
    const twin = dark.find((d) => d.name === e.name);
    return { name: e.path.filter((p) => p !== 'light').join('/'), type: e.type ?? 'string',
      values: { Light: varOf(e, 'light'), Dark: twin ? varOf(twin, 'dark') : varOf(e, 'light') } };
  });
  writeFileSync(join(outDir, 'tokens.figma.json'), JSON.stringify({
    collections: [
      { name: 'Primitives', modes: ['Value'], variables: primitives },
      { name: 'Semantic', modes: ['Light', 'Dark'], variables: semantic },
    ],
  }, null, 2));
  written.push('tokens.figma.json');
}

console.log(`tokens: ${entries.length} (${base.length} static, ${light.length} light, ${dark.length} dark) → ${written.map((f) => join(outDir, f)).join(', ')}`);
